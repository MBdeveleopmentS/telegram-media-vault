def fmt_dt(dt: datetime | None) -> str:
    if dt is None:
        return NEVER
    return dt.astimezone(TZ).strftime("%d/%m/%Y %H:%M")


def fmt_date(dt: datetime) -> str:
    return dt.astimezone(TZ).strftime("%d/%m/%Y")


def days_text(n: int) -> str:
    return "יום אחד" if n == 1 else f"{n} ימים"


